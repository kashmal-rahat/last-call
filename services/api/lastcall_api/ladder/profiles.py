"""Produce profile resolution and storage using Gemini 3.8 Flash (Module 3)."""

import asyncio
from datetime import datetime, timezone
import json
import logging
from pathlib import Path
from typing import Any, NamedTuple

from google import genai
from google.genai import types
from pydantic import BaseModel

from lastcall_api.gemini_call import (
    CallUsage,
    GeminiCallError,
    call_structured,
    get_genai_client,
)
from lastcall_api.ladder.keys import produce_key
from lastcall_shared.config import get_settings
from lastcall_shared.logging_utils import setup_structured_logging
from lastcall_shared.models import (
    ProduceProfile,
    ShelfLifeBand,
    StageProfile,
)

logger = setup_structured_logging(service_name="ladder_profiles")

PROFILE_PROMPT_VERSION = "1"

PROMPT_FILE = Path(__file__).parent / "profile_prompt.md"
SYSTEM_PROMPT = PROMPT_FILE.read_text(encoding="utf-8")

BAND_ORDER: dict[ShelfLifeBand, int] = {
    "under_6h": 0,
    "6_to_24h": 1,
    "1_to_3_days": 2,
    "over_3_days": 3,
}

ORDER_TO_BAND: dict[int, ShelfLifeBand] = {
    0: "under_6h",
    1: "6_to_24h",
    2: "1_to_3_days",
    3: "over_3_days",
}


class ResolveProfilesStats(NamedTuple):
    calls: int
    generated: int
    fallbacks: int


class ProfileOut(BaseModel):
    """Schema for individual produce profile generated by Gemini."""

    input_name: str
    note: str
    fresh: StageProfile
    ripening: StageProfile
    overripe: StageProfile
    overripe_ok_for_cattle: bool
    spoiled_ok_for_cattle: bool


class ProfilesOut(BaseModel):
    """Container schema for batch profile output."""

    profiles: list[ProfileOut]


def check_profile(p: ProduceProfile) -> tuple[ProduceProfile, list[str]]:
    """Applies generic code rules before saving.

    1. Monotonic shelf life: ripening <= fresh, overripe <= ripening in band order.
    2. Note <= 120 chars, stripped.
    3. Food-waste hierarchy (C2): charity is always True for fresh, ripening and overripe (edible stages).
    """
    notes: list[str] = []
    fresh_order = BAND_ORDER.get(p.fresh.sellable_for, 0)
    rip_order = BAND_ORDER.get(p.ripening.sellable_for, 0)
    over_order = BAND_ORDER.get(p.overripe.sellable_for, 0)

    # 1. Monotonic shelf life check
    if rip_order > fresh_order:
        notes.append(f"ripening band {p.ripening.sellable_for} > fresh band {p.fresh.sellable_for}; capped to fresh")
        rip_order = fresh_order
        p.ripening.sellable_for = ORDER_TO_BAND[rip_order]

    if over_order > rip_order:
        notes.append(f"overripe band {p.overripe.sellable_for} > ripening band {p.ripening.sellable_for}; capped to ripening")
        over_order = rip_order
        p.overripe.sellable_for = ORDER_TO_BAND[over_order]

    # 2. Note <= 120 chars, stripped
    cleaned_note = p.note.strip()
    if len(cleaned_note) > 120:
        cleaned_note = cleaned_note[:120].rstrip()
        notes.append("note truncated to 120 chars")
    p.note = cleaned_note

    # 3. Food-waste hierarchy: people first (C2)
    for stage_name in ("fresh", "ripening", "overripe"):
        stage_obj = getattr(p, stage_name)
        if not stage_obj.charity:
            stage_obj.charity = True
            notes.append(f"{stage_name}.charity set to True (food-waste hierarchy: people first)")

    if notes:
        logger.info(
            "check_profile corrections applied",
            extra={"produce_key": p.key, "corrections": len(notes)},
        )

    return p, notes


def fallback_profile(name: str) -> ProduceProfile:
    """Returns a cautious, generic profile used when Gemini fails or name is unknown. Not saved."""
    pkey = produce_key(name)
    fresh_sp = StageProfile(sellable_for="1_to_3_days", juice_shop=False, restaurant=True, bakery=False, charity=True)
    rip_sp = StageProfile(sellable_for="6_to_24h", juice_shop=False, restaurant=True, bakery=False, charity=True)
    over_sp = StageProfile(sellable_for="under_6h", juice_shop=False, restaurant=True, bakery=False, charity=True)

    return ProduceProfile(
        key=f"{pkey}__fallback",
        name=name,
        note="Generic fallback profile",
        fresh=fresh_sp,
        ripening=rip_sp,
        overripe=over_sp,
        spoiled_ok_for_cattle=False,
        overripe_ok_for_cattle=False,
        source="fallback",
        model="",
        prompt_version=PROFILE_PROMPT_VERSION,
        created_at=datetime.now(timezone.utc),
    )


def build_profile_config() -> types.GenerateContentConfig:
    """Builds Gemini config for produce profiles complying with D30."""
    return types.GenerateContentConfig(
        system_instruction=SYSTEM_PROMPT,
        response_mime_type="application/json",
        response_schema=ProfilesOut,
        thinking_config=types.ThinkingConfig(thinking_level="low"),
    )


async def resolve_profiles(
    names: list[str],
    *,
    store: Any,
    client: genai.Client | None = None,
    deadline: float,
) -> tuple[dict[str, ProduceProfile], CallUsage, ResolveProfilesStats]:
    """Resolves produce profiles for names using batch store lookup and single Gemini call for missing ones."""
    total_usage = CallUsage(input_tokens=0, output_tokens=0, cached_tokens=0)
    empty_stats = ResolveProfilesStats(calls=0, generated=0, fallbacks=0)
    if not names:
        return {}, total_usage, empty_stats

    # Dedupe names by produce_key
    unique_names: dict[str, str] = {}
    for n in names:
        pkey = produce_key(n)
        if pkey and pkey not in unique_names:
            unique_names[pkey] = n

    resolved_by_key: dict[str, ProduceProfile] = {}

    # Unknown produce gets fallback immediately without store read or Gemini call
    for pkey, raw_name in list(unique_names.items()):
        if pkey == "unknown_produce" or not pkey:
            resolved_by_key[pkey] = fallback_profile(raw_name)

    # 1. Read both keys per remaining name (__manager and __v{N}) in one batch read
    remaining_pkeys = [k for k in unique_names if k not in resolved_by_key]
    keys_to_fetch: list[str] = []
    for pkey in remaining_pkeys:
        keys_to_fetch.extend([f"{pkey}__manager", f"{pkey}__v{PROFILE_PROMPT_VERSION}"])

    stored_profiles = await store.get_profiles(keys_to_fetch)

    missing_names: list[str] = []
    for pkey in remaining_pkeys:
        raw_name = unique_names[pkey]
        manager_key = f"{pkey}__manager"
        gemini_key = f"{pkey}__v{PROFILE_PROMPT_VERSION}"

        if manager_key in stored_profiles:
            resolved_by_key[pkey] = stored_profiles[manager_key]
        elif gemini_key in stored_profiles:
            resolved_by_key[pkey] = stored_profiles[gemini_key]
        else:
            missing_names.append(raw_name)

    gemini_calls = 0
    profiles_generated = 0

    # 2. Call Gemini for missing names in one structured call
    if missing_names:
        if client is None:
            client = get_genai_client()

        user_content = "Produce names: " + json.dumps(missing_names)
        config = build_profile_config()

        try:
            gemini_calls = 1
            out, usage, attempts, was_hedged = await call_structured(
                client=client,
                contents=[user_content],
                config=config,
                schema=ProfilesOut,
                deadline=deadline,
                max_attempts=2,
                per_attempt_timeout=15.0,
                hedge_after_s=8.0,
                label="ProduceProfile",
            )
            total_usage = usage
            model_name = get_settings().GEMINI_FLASH_MODEL

            # Match answers back by produce_key(input_name)
            answers_by_key = {produce_key(item.input_name): item for item in out.profiles}

            for raw_name in missing_names:
                pkey = produce_key(raw_name)
                item = answers_by_key.get(pkey)
                if item is not None:
                    prof = ProduceProfile(
                        key=f"{pkey}__v{PROFILE_PROMPT_VERSION}",
                        name=raw_name,
                        note=item.note,
                        fresh=item.fresh,
                        ripening=item.ripening,
                        overripe=item.overripe,
                        spoiled_ok_for_cattle=item.spoiled_ok_for_cattle,
                        overripe_ok_for_cattle=item.overripe_ok_for_cattle,
                        source="gemini",
                        model=model_name,
                        prompt_version=PROFILE_PROMPT_VERSION,
                        created_at=datetime.now(timezone.utc),
                    )
                    checked_p, _ = check_profile(prof)
                    profiles_generated += 1

                    # I1 & I2: save handling
                    try:
                        created = await store.create_profile(checked_p)
                        if created:
                            resolved_by_key[pkey] = checked_p
                        else:
                            # Lost create race: read back stored profile to ensure consistency
                            stored_back = await store.get_profiles([checked_p.key])
                            if checked_p.key in stored_back:
                                resolved_by_key[pkey] = stored_back[checked_p.key]
                            else:
                                resolved_by_key[pkey] = checked_p
                    except Exception as save_err:
                        # Non-fatal write error: keep using generated profile for this request
                        logger.warning(
                            "Failed to save produce profile to store",
                            extra={"save_error": type(save_err).__name__},
                        )
                        resolved_by_key[pkey] = checked_p
                else:
                    resolved_by_key[pkey] = fallback_profile(raw_name)

        except GeminiCallError as exc:
            logger.warning(
                "Gemini profile call failed, falling back",
                extra={"missing_count": len(missing_names)},
            )
            for raw_name in missing_names:
                pkey = produce_key(raw_name)
                resolved_by_key[pkey] = fallback_profile(raw_name)

    # Count fallbacks across all unique produce
    fallback_count = sum(1 for p in resolved_by_key.values() if p.source == "fallback")

    # Map back to caller input names
    result_by_name: dict[str, ProduceProfile] = {}
    for n in names:
        pkey = produce_key(n)
        prof = resolved_by_key.get(pkey) or fallback_profile(n)
        result_by_name[n] = prof
        result_by_name[pkey] = prof

    stats = ResolveProfilesStats(
        calls=gemini_calls,
        generated=profiles_generated,
        fallbacks=fallback_count,
    )
    return result_by_name, total_usage, stats
